import { bench, describe } from 'vitest';

import type { PdfBuildType } from '@/resources/pdf/schema.js';

import { buildPdfDocument } from '@/resources/pdf/builder.js';

/**
 * Realistic build payload: a title, a subtitle, ~120 paragraphs and a page
 * number footer — roughly what `/pdf/build` is expected to produce per request.
 * @returns A validated-shape build payload.
 */
const makePayload = (): PdfBuildType =>
  ({
    metadata: { author: 'file-fly', title: 'Throughput Report' },
    pages: [
      {
        elements: [
          { size: 22, text: 'Throughput Report', type: 'text', x: 72, y: 40 },
          { size: 11, text: 'Generated by the perf bench fixture.', type: 'text', x: 72, y: 64 },
          ...Array.from({ length: 120 }, (_, index) => ({
            size: 10,
            text: `Paragraph ${index + 1}. The quick brown fox jumps over the lazy dog.`,
            type: 'text' as const,
            w: 468,
            x: 72,
            y: 100 + index * 5,
          })),
          { format: 'Page {n} of {total}', size: 9, type: 'pageNumber', x: 72, y: 760 },
        ],
        size: 'a4',
      },
    ],
  }) as unknown as PdfBuildType;

describe('buildPdfDocument', () => {
  const payload = makePayload();
  bench('builds a 120-paragraph document', async () => {
    const bytes = await buildPdfDocument(payload);
    if (bytes.length < 1024) {
      throw new Error('pdf unexpectedly small');
    }
  }, {
    throws: true,
  });
});
