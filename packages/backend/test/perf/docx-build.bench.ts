import type { Document as DocxDocument } from 'docx';

import { Document, Packer } from 'docx';
import { bench, describe } from 'vitest';

import type { DocxBuildType } from '@/resources/docx/schema.js';

import { buildBlock, buildSectionOptions } from '@/resources/docx/elements.js';

/**
 * Realistic build payload: ~120 paragraphs of body text in a single section,
 * mirroring what `/docx/build` accepts.
 * @returns A validated-shape build payload.
 */
const makePayload = (): DocxBuildType =>
  ({
    sections: [
      {
        children: [
          { runs: [{ bold: true, text: 'Throughput Report' }], type: 'paragraph' },
          { runs: [{ text: 'Generated by the perf bench fixture.' }], type: 'paragraph' },
          ...Array.from({ length: 120 }, (_, index) => ({
            runs: [{ text: `Paragraph ${index + 1}. The quick brown fox jumps over the lazy dog.` }],
            type: 'paragraph' as const,
          })),
        ],
      },
    ],
  }) as unknown as DocxBuildType;

/**
 * Builds the worker's Document from the payload the same way the docx worker does.
 * @param payload - The validated build payload.
 * @returns A docx Document.
 */
const build = (payload: DocxBuildType): DocxDocument =>
  new Document({
    sections: payload.sections.map((section) => ({
      children: section.children.flatMap((element) => buildBlock(element)),
      ...buildSectionOptions(section),
    })),
  });

describe('docx build (elements + pack)', () => {
  bench('builds and packs a 120-paragraph document', async () => {
    const document = build(makePayload());
    const bytes = await Packer.toBuffer(document);
    if (bytes.length < 1024) {
      throw new Error('docx unexpectedly small');
    }
  }, {
    throws: true,
  });
});
